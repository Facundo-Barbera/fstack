# shellcheck shell=bash
# fstack gate checks. Sourced by run.sh after lib.sh.

# Existing debt is the baseline: a file fails only if it is over the cap and grew.
check_max_lines() {
  gate_on max-lines || return 0
  local max added path new old
  max=$(cfg max-lines 400)
  while IFS=$'\t' read -r added _ path; do
    [ "$added" = "-" ] && continue
    [ -n "$path" ] || continue
    new=$(new_blob "$path" | count_lines)
    [ "$new" -gt "$max" ] || continue
    old=$(old_blob "$path" | count_lines)
    if [ "$new" -gt "$old" ]; then
      report max-lines "$path has $new lines (cap $max, was $old); split it instead of growing it"
    fi
  done < <(scope_diff --numstat --diff-filter=ACMR)
}

is_doc_path() {
  case $1 in
    *.md | *.mdx | *.rst | *.txt | *.adoc) return 0 ;;
  esac
  return 1
}

# Lines that are prose (docs or comments) versus code, counted on added lines only.
check_doc_ratio() {
  gate_on doc-ratio || return 0
  local ratio min file="" line prose=0 code=0
  ratio=$(cfg doc-ratio 0.5)
  min=$(cfg doc-ratio-min 20)
  while IFS= read -r line; do
    case $line in
      '+++ b/'*) file=${line#+++ b/}; continue ;;
      '+++ '* | '---'*) continue ;;
      +*) line=${line#+} ;;
      *) continue ;;
    esac
    [[ $line =~ ^[[:space:]]*$ ]] && continue
    if is_doc_path "$file"; then
      prose=$((prose + 1))
    elif [[ $line =~ ^[[:space:]]*(#!) ]]; then
      code=$((code + 1))
    elif [[ $line =~ ^[[:space:]]*(#|//|/\*|\*|--|\<!--|\"\"\"|;) ]]; then
      prose=$((prose + 1))
    else
      code=$((code + 1))
    fi
  done < <(scope_diff -U0 --diff-filter=ACMR)
  [ "$prose" -ge "$min" ] || return 0
  if awk -v p="$prose" -v c="$code" -v r="$ratio" 'BEGIN { exit !(p > r * (c > 0 ? c : 1)) }'; then
    report doc-ratio "added $prose lines of docs/comments vs $code of code (limit ${ratio}x); keep comments to the why"
  fi
}

# Tool-specific agent configs that duplicate AGENTS.md or get generated by adapters.
is_agent_config() {
  case $1 in
    CLAUDE.md | */CLAUDE.md | GEMINI.md | */GEMINI.md | AGENTS.override.md | */AGENTS.override.md) return 0 ;;
    .cursorrules | .windsurfrules | .clinerules | .clinerules/* | .roo/* | .roorules) return 0 ;;
    .cursor/rules/* | .cursor/hooks.json | .windsurf/* | .continue/* | .aider* | CONVENTIONS.md) return 0 ;;
    .github/copilot-instructions.md | .github/instructions/*) return 0 ;;
    .claude/settings.json | .claude/skills/* | .codex/hooks.json | .codex/config.toml) return 0 ;;
  esac
  return 1
}

check_new_files() {
  gate_on new-files || return 0
  local allow adr path base ok a
  allow=$(cfg md-allowlist "README.md AGENTS.md SKILL.md INDEX.md")
  adr=$(cfg adr-dir "")
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    if is_agent_config "$path"; then
      report new-files "new agent/tool config $path; rules live in AGENTS.md and fstack generates per-tool files"
      continue
    fi
    case $path in *.md | *.mdx) ;; *) continue ;; esac
    base=${path##*/}
    ok=0
    for a in $allow; do [ "$base" = "$a" ] && ok=1; done
    if [ -n "$adr" ] && [[ $path == "$adr"/* ]]; then ok=1; fi
    [ "$ok" = 1 ] || report new-files "new markdown $path is outside the allowlist ($allow); put reports in the PR body"
  done < <(scope_diff --name-only --diff-filter=A)
}

# gitleaks always runs with --redact so a finding never prints the secret itself.
check_secrets() {
  gate_on secrets || return 0
  if ! command -v gitleaks >/dev/null 2>&1; then
    report secrets "gitleaks is not installed: secrets NOT VERIFIED"
    return 0
  fi
  local base out rc args=(git --redact --no-banner)
  if [ "${FSTACK_SCOPE:-branch}" = staged ]; then
    args+=(--staged)
  else
    base=$(base_commit)
    [ "$base" = "$EMPTY_TREE" ] || args+=("--log-opts=$base..HEAD")
  fi
  out=$(gitleaks "${args[@]}" "$FSTACK_ROOT" 2>&1)
  rc=$?
  if [ "$rc" -ne 0 ]; then
    printf '%s\n' "$out" | grep -E 'Finding|File|Line|RuleID|leaks found' >&2 || true
    report secrets "gitleaks reported findings (exit $rc)"
  fi
}

AI_COAUTHOR_RE='^(co-authored-by|generated-by|assisted-by):.*(claude|anthropic|openai|codex|copilot|cursor|gpt|gemini|devin|aider)'
STAMP_RE='^Verified: [^[:space:]]+'

# One message: needs a Verified trailer and no AI co-author trailers.
check_stamp_text() {
  local label=$1 text
  text=$(grep -v '^#')
  if ! printf '%s\n' "$text" | grep -Eq "$STAMP_RE"; then
    report stamp "$label has no 'Verified: <skill> <evidence>' trailer (use 'Verified: none' if nothing ran)"
  fi
  if printf '%s\n' "$text" | grep -Eiq "$AI_COAUTHOR_RE"; then
    report stamp "$label carries an AI co-author trailer; remove it"
  fi
  if printf '%s\n' "$text" | grep -Eiq 'generated with \[?(claude|codex|cursor)'; then
    report stamp "$label carries an AI attribution line; remove it"
  fi
}

check_stamp_msg() {
  gate_on stamp || return 0
  [ -f "${1:-}" ] || return 0
  check_stamp_text "commit message" <"$1"
}

check_stamp_range() {
  gate_on stamp || return 0
  local base sha
  base=$(base_commit)
  [ "$base" = "$EMPTY_TREE" ] && return 0
  for sha in $(git rev-list --no-merges "$base..HEAD"); do
    # Process substitution, not a pipe: a pipe would run report in a subshell and lose the failure.
    check_stamp_text "commit ${sha:0:9}" < <(git log -1 --format=%B "$sha")
  done
}

# PR body comes from a file, an env var, or the GitHub Actions event payload.
pr_body() {
  if [ -n "${FSTACK_PR_BODY_FILE:-}" ] && [ -f "$FSTACK_PR_BODY_FILE" ]; then
    cat "$FSTACK_PR_BODY_FILE"
  elif [ -n "${FSTACK_PR_BODY:-}" ]; then
    printf '%s\n' "$FSTACK_PR_BODY"
  elif [ -n "${GITHUB_EVENT_PATH:-}" ] && [ -f "$GITHUB_EVENT_PATH" ] && command -v jq >/dev/null; then
    jq -r '.pull_request.body // empty' "$GITHUB_EVENT_PATH"
  fi
}

check_removed() {
  gate_on removed || return 0
  local body
  body=$(pr_body)
  [ -n "$body" ] || return 0
  if ! printf '%s\n' "$body" | grep -Eiq '^[#*[:space:]]*(removed|what i removed|qu[eé] quit[eé])[*[:space:]]*:?'; then
    report removed "PR body has no 'Removed:' section; say what this change deletes (or 'Removed: nothing, because ...')"
  fi
}
