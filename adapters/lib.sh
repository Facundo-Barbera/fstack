# shellcheck shell=bash
# Shared by adapter generators. Sourced with TARGET set to the target repo root.
set -o pipefail

# Never clobber a file the repo tracks: that file belongs to the team, not to fstack.
writable() {
  local rel=$1
  if git -C "$TARGET" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
    echo "fstack: $rel is tracked by git; left untouched (merge fstack's version by hand)" >&2
    return 1
  fi
  # An untracked file fstack did not generate before is the user's; leave it alone.
  if [ -e "$TARGET/$rel" ] || [ -L "$TARGET/$rel" ]; then
    if ! printf '%s\n' "${FSTACK_PREV_GENERATED:-}" | grep -Fxq -- "$rel"; then
      echo "fstack: $rel exists and was not generated by fstack; left untouched" >&2
      return 1
    fi
  fi
  return 0
}

# emit <relative path>: writes stdin to the path and prints the path for .gitignore.
emit() {
  local rel=$1
  writable "$rel" || { cat >/dev/null; return 0; }
  mkdir -p "$(dirname "$TARGET/$rel")"
  cat >"$TARGET/$rel"
  printf '%s\n' "$rel"
}

# emit_link <relative path> <link target>
emit_link() {
  local rel=$1 dest=$2
  if [ -L "$TARGET/$rel" ] && [ "$(readlink "$TARGET/$rel")" = "$dest" ]; then
    printf '%s\n' "$rel"
    return 0
  fi
  writable "$rel" || return 0
  mkdir -p "$(dirname "$TARGET/$rel")"
  ln -sfn "$dest" "$TARGET/$rel"
  printf '%s\n' "$rel"
}
